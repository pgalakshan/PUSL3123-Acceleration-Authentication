%% Baseline multiclass neural network
clear;
clc;
close all;

scriptPath = mfilename('fullpath');
projectRoot = fileparts(fileparts(scriptPath));

dataDir = fullfile(projectRoot, 'CW-Data');
tableDir = fullfile(projectRoot, 'results', 'tables');
figureDir = fullfile(projectRoot, 'results', 'figures');

if ~exist(tableDir, 'dir')
    mkdir(tableDir);
end

if ~exist(figureDir, 'dir')
    mkdir(figureDir);
end

%% Configuration

users = compose('U%02d', 1:10);

domains = {
    'FreqD'
    'TimeD'
    'TimeD_FreqD'
};

hiddenNeurons = 24;
developmentRepeats = 5;
finalRepeats = 5;

validationSamplesPerUser = 8;
maxEpochs = 400;

fprintf('\nStage 4 - Baseline Neural Network\n');
fprintf('=================================\n\n');

fprintf('Model: 10-class pattern recognition network\n');
fprintf('Hidden neurons: %d\n', hiddenNeurons);
fprintf('Development repeats: %d\n', developmentRepeats);
fprintf('Validation samples per user: %d\n\n', ...
    validationSamplesPerUser);

%% FDay-only domain selection

developmentRows = cell(0, 11);
developmentRow = 1;

for d = 1:numel(domains)

    domain = domains{d};

    fprintf('Development testing: %s\n', domain);

    [X, labels] = loadDomainData( ...
        dataDir, ...
        domain, ...
        'FDay', ...
        users);

    for repeat = 1:developmentRepeats

        rng(4100 + d * 100 + repeat, 'twister');

        trainMask = false(size(labels));
        validationMask = false(size(labels));

        %% Stratified FDay split

        for u = 1:10

            userIndices = find(labels == u);

            randomOrder = ...
                userIndices(randperm(numel(userIndices)));

            validationIndices = ...
                randomOrder(1:validationSamplesPerUser);

            trainingIndices = ...
                randomOrder(validationSamplesPerUser + 1:end);

            validationMask(validationIndices) = true;
            trainMask(trainingIndices) = true;
        end

        XTrain = X(trainMask, :);
        yTrain = labels(trainMask);

        XValidation = X(validationMask, :);
        yValidation = labels(validationMask);

        %% Standardisation fitted on training data

        mu = mean(XTrain, 1);
        sigma = std(XTrain, 0, 1);

        sigma(sigma == 0) = 1;

        XTrainZ = ...
            (XTrain - mu) ./ sigma;

        XValidationZ = ...
            (XValidation - mu) ./ sigma;

        %% Baseline neural network

        network = patternnet( ...
            hiddenNeurons, ...
            'trainscg');

        network.performFcn = 'crossentropy';
        network.divideFcn = 'dividetrain';

        network.trainParam.epochs = maxEpochs;
        network.trainParam.showWindow = false;
        network.trainParam.showCommandLine = false;

        % External standardisation is already applied.
        network.inputs{1}.processFcns = {};

        targets = ...
            full(ind2vec(yTrain'));

        network = train( ...
            network, ...
            XTrainZ', ...
            targets);

        validationScores = ...
            network(XValidationZ');

        metrics = authenticationMetrics( ...
            yValidation, ...
            validationScores);

        developmentRows(developmentRow, :) = { ...
            domain, ...
            repeat, ...
            metrics.Accuracy, ...
            metrics.MacroPrecision, ...
            metrics.MacroRecall, ...
            metrics.MacroF1, ...
            metrics.MacroSpecificity, ...
            metrics.MeanFAR, ...
            metrics.MeanFRR, ...
            metrics.MeanEER, ...
            metrics.MeanAUC ...
            };

        developmentRow = developmentRow + 1;
    end
end

%% Save development runs

