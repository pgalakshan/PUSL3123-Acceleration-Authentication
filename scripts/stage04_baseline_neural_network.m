    fprintf( ...
        'Cross-day repeat %d/%d\n', ...
        repeat, ...
        finalRepeats);

    rng(8100 + repeat, 'twister');

    %% FDay standardisation

    mu = mean(XFDay, 1);
    sigma = std(XFDay, 0, 1);

    sigma(sigma == 0) = 1;

    XTrainZ = ...
        (XFDay - mu) ./ sigma;

    XTestZ = ...
        (XMDay - mu) ./ sigma;

    %% Train on all FDay

    network = patternnet( ...
        hiddenNeurons, ...
        'trainscg');

    network.performFcn = 'crossentropy';
    network.divideFcn = 'dividetrain';

    network.trainParam.epochs = maxEpochs;
    network.trainParam.showWindow = false;
    network.trainParam.showCommandLine = false;

    network.inputs{1}.processFcns = {};

    targets = ...
        full(ind2vec(yFDay'));

    network = train( ...
        network, ...
        XTrainZ', ...
        targets);

    %% MDay evaluation

    scores = ...
        network(XTestZ');

    [metrics, userMetrics, predictedLabels] = ...
        authenticationMetrics( ...
        yMDay, ...
        scores);

    crossDayRows(crossDayRow, :) = { ...
        selectedDomain, ...
        repeat, ...
        metrics.Accuracy, ...
        metrics.MacroPrecision, ...
        metrics.MacroRecall, ...
        metrics.MacroF1, ...
        metrics.MacroSpecificity, ...
        metrics.MeanFAR, ...
        metrics.MeanFRR, ...
        metrics.MeanEER, ...
        metrics.MeanAUC ...
        };

    crossDayRow = crossDayRow + 1;

    for u = 1:10

        crossDayUserRows(crossDayUserRow, :) = { ...
            repeat, ...
            u, ...
            userMetrics.Accuracy(u), ...
            userMetrics.Precision(u), ...
            userMetrics.Recall(u), ...
            userMetrics.Specificity(u), ...
            userMetrics.F1(u), ...
            userMetrics.FAR(u), ...
            userMetrics.FRR(u), ...
            userMetrics.EER(u) ...
            };

