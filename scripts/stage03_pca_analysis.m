for r = 1:height(PCASummary)

    fprintf( ...
        '%-12s | PC1+PC2 %.2f%% | 90%% PCs %d | 95%% PCs %d | FDay Sep %.3f | MDay Sep %.3f\n', ...
        PCASummary.Domain{r}, ...
        PCASummary.PC1PC2VariancePercent(r), ...
        PCASummary.PCsFor90Percent(r), ...
        PCASummary.PCsFor95Percent(r), ...
        PCASummary.FDaySeparationRatio(r), ...
        PCASummary.MDaySeparationRatio(r));
end

