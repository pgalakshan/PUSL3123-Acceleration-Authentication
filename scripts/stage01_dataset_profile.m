%% Dataset profiling
clear;
clc;
close all;

scriptPath = mfilename('fullpath');
projectRoot = fileparts(fileparts(scriptPath));

dataDir = fullfile(projectRoot, 'CW-Data');
tableDir = fullfile(projectRoot, 'results', 'tables');

if ~exist(tableDir, 'dir')
    mkdir(tableDir);
end

%% Find dataset files

files = dir(fullfile(dataDir, '*.mat'));

fprintf('\nDataset files found: %d\n', numel(files));

if numel(files) ~= 60
    warning('Expected 60 MAT files but found %d.', numel(files));
end

%% Profile each file

profileRows = cell(0, 13);

row = 1;

for k = 1:numel(files)

    fileName = files(k).name;
    filePath = fullfile(files(k).folder, fileName);

    token = regexp( ...
        fileName, ...
        '^(U\d{2})_Acc_(FreqD|TimeD|TimeD_FreqD)_(FDay|MDay)\.mat$', ...
        'tokens', ...
        'once');

    if isempty(token)
        warning('Unexpected filename: %s', fileName);
        continue;
    end

    userID = token{1};
    domain = token{2};
    day = token{3};

    switch domain
        case 'FreqD'
            expectedFeatures = 43;

        case 'TimeD'
            expectedFeatures = 88;

        case 'TimeD_FreqD'
            expectedFeatures = 131;

        otherwise
            expectedFeatures = NaN;
    end

    S = load(filePath);

    variableNames = fieldnames(S);

    if isempty(variableNames)
        warning('No MATLAB variable in %s', fileName);
        continue;
    end

    variableName = variableNames{1};
    X = S.(variableName);

    samples = size(X, 1);
    features = size(X, 2);

    dimensionValid = ...
        samples == 36 && ...
        features == expectedFeatures;

    nanCount = sum(isnan(X), 'all');
    infCount = sum(isinf(X), 'all');

    meanValue = mean(X, 'all', 'omitnan');
    stdValue = std(X, 0, 'all', 'omitnan');

    minValue = min(X, [], 'all');
    maxValue = max(X, [], 'all');

    profileRows(row,:) = { ...
        userID, ...
        domain, ...
        day, ...
        fileName, ...
        variableName, ...
        samples, ...
        features, ...
        expectedFeatures, ...
        dimensionValid, ...
        nanCount, ...
        infCount, ...
        meanValue, ...
        stdValue ...
        };

    row = row + 1;
end

DatasetProfile = cell2table( ...
    profileRows, ...
    'VariableNames', { ...
    'User', ...
    'Domain', ...
    'Day', ...
    'FileName', ...
    'VariableName', ...
    'Samples', ...
    'Features', ...
    'ExpectedFeatures', ...
    'DimensionValid', ...
    'NaNCount', ...
    'InfCount', ...
    'GlobalMean', ...
    'GlobalSD' ...
    });

writetable( ...
    DatasetProfile, ...
    fullfile(tableDir, 'dataset_profile.csv'));

%% Dataset quality summary

totalFiles = height(DatasetProfile);

validDimensions = sum(DatasetProfile.DimensionValid);

totalNaN = sum(DatasetProfile.NaNCount);
totalInf = sum(DatasetProfile.InfCount);

QualitySummary = table( ...
    totalFiles, ...
    validDimensions, ...
    totalNaN, ...
    totalInf, ...
    'VariableNames', { ...
    'Files', ...
    'ValidDimensions', ...
    'TotalNaN', ...
    'TotalInf' ...
    });

writetable( ...
    QualitySummary, ...
    fullfile(tableDir, 'dataset_quality_summary.csv'));

%% Cross-day comparison

users = compose('U%02d', 1:10);

domains = { ...
    'FreqD', ...
    'TimeD', ...
    'TimeD_FreqD' ...
    };

dayRows = cell(0, 8);

row = 1;

for u = 1:numel(users)

    for d = 1:numel(domains)

        userID = users{u};
        domain = domains{d};

        fdayFile = fullfile( ...
            dataDir, ...
            sprintf('%s_Acc_%s_FDay.mat', userID, domain));

        mdayFile = fullfile( ...
            dataDir, ...
            sprintf('%s_Acc_%s_MDay.mat', userID, domain));

        SF = load(fdayFile);
        SM = load(mdayFile);

        fnF = fieldnames(SF);
        fnM = fieldnames(SM);

        XF = SF.(fnF{1});
        XM = SM.(fnM{1});

        exactDuplicate = isequal(XF, XM);

        maxAbsDifference = ...
            max(abs(XF - XM), [], 'all');

        meanAbsDifference = ...
            mean(abs(XF - XM), 'all');

        fdayMeanVector = mean(XF, 1);
        mdayMeanVector = mean(XM, 1);

        meanVectorDistance = ...
            norm(fdayMeanVector - mdayMeanVector);

        fdayVariance = ...
            mean(var(XF, 0, 1));

        mdayVariance = ...
            mean(var(XM, 0, 1));

        dayRows(row,:) = { ...
            userID, ...
            domain, ...
            exactDuplicate, ...
            maxAbsDifference, ...
            meanAbsDifference, ...
            meanVectorDistance, ...
            fdayVariance, ...
            mdayVariance ...
            };

        row = row + 1;
    end
end

CrossDaySummary = cell2table( ...
    dayRows, ...
    'VariableNames', { ...
    'User', ...
    'Domain', ...
    'ExactDuplicate', ...
    'MaximumAbsoluteDifference', ...
    'MeanAbsoluteDifference', ...
    'MeanVectorDistance', ...
    'FDayMeanVariance', ...
    'MDayMeanVariance' ...
    });

writetable( ...
    CrossDaySummary, ...
    fullfile(tableDir, 'cross_day_consistency.csv'));

%% Domain dimensions

Domain = [ ...
    "Frequency"; ...
    "Time"; ...
    "Combined" ...
    ];

Features = [43; 88; 131];

SamplesPerUserPerDay = [36; 36; 36];

Users = [10; 10; 10];

DomainSummary = table( ...
    Domain, ...
    Features, ...
    SamplesPerUserPerDay, ...
    Users);

writetable( ...
    DomainSummary, ...
    fullfile(tableDir, 'dataset_domain_summary.csv'));

%% Display results

fprintf('\nDataset profile complete.\n\n');

fprintf('Files checked       : %d\n', totalFiles);
fprintf('Valid dimensions    : %d/%d\n', ...
    validDimensions, totalFiles);
fprintf('NaN values          : %d\n', totalNaN);
fprintf('Infinite values     : %d\n\n', totalInf);

duplicates = ...
    CrossDaySummary(CrossDaySummary.ExactDuplicate, :);

fprintf('Exact FDay/MDay duplicates:\n');

if isempty(duplicates)
    fprintf('None\n');
else
    disp(duplicates(:, {'User','Domain','ExactDuplicate'}));
end

fprintf('\nGenerated tables:\n');
fprintf('dataset_profile.csv\n');
fprintf('dataset_quality_summary.csv\n');
fprintf('cross_day_consistency.csv\n');
fprintf('dataset_domain_summary.csv\n');