%% Local functions

function [XAll, labels] = ...
    loadDomainData(dataDir, domain, dayName, users)

    XAll = [];
    labels = [];

    for i = 1:numel(users)

        userID = users(i);

        filePath = fullfile( ...
            dataDir, ...
            sprintf( ...
            'U%02d_Acc_%s_%s.mat', ...
            userID, ...
            domain, ...
            dayName));

        S = load(filePath);

        variableNames = ...
            fieldnames(S);

        X = ...
            S.(variableNames{1});

        XAll = [
            XAll;
            X
        ];

        labels = [
            labels;
            repmat(userID, size(X, 1), 1)
        ];
    end
end


function [metrics, userTable] = ...
    authenticationMetrics(trueLabels, scores)

    classCount = size(scores, 1);

    predictedLabels = ...
        vec2ind(scores)';

    accuracy = ...
        mean(predictedLabels == trueLabels);

    userAccuracy = zeros(classCount, 1);
    precision = zeros(classCount, 1);
    recall = zeros(classCount, 1);
    specificity = zeros(classCount, 1);
    f1 = zeros(classCount, 1);
    far = zeros(classCount, 1);
    frr = zeros(classCount, 1);
    eer = zeros(classCount, 1);
    auc = zeros(classCount, 1);

    for u = 1:classCount

        genuine = ...
            trueLabels == u;

        acceptedAsUser = ...
            predictedLabels == u;

        TP = sum(genuine & acceptedAsUser);
        FN = sum(genuine & ~acceptedAsUser);

        FP = sum(~genuine & acceptedAsUser);
        TN = sum(~genuine & ~acceptedAsUser);

        userAccuracy(u) = ...
            (TP + TN) / ...
            (TP + TN + FP + FN + eps);

        precision(u) = ...
            TP / ...
            (TP + FP + eps);

        recall(u) = ...
            TP / ...
            (TP + FN + eps);

        specificity(u) = ...
            TN / ...
            (TN + FP + eps);

        f1(u) = ...
            2 * precision(u) * recall(u) / ...
            (precision(u) + recall(u) + eps);

        far(u) = ...
            FP / ...
            (FP + TN + eps);

        frr(u) = ...
            FN / ...
            (TP + FN + eps);

        binaryLabels = ...
            double(genuine);

        userScores = ...
            scores(u, :)';

        [rocFPR, rocTPR, ~, aucValue] = ...
            perfcurve( ...
            binaryLabels, ...
            userScores, ...
            1);

        rocFNR = ...
            1 - rocTPR;

        [~, eerIndex] = ...
            min(abs(rocFPR - rocFNR));

        eer(u) = ...
            (rocFPR(eerIndex) + ...
            rocFNR(eerIndex)) / 2;

        auc(u) = ...
            aucValue;
    end

    metrics = struct();

    metrics.Accuracy = ...
        accuracy;

    metrics.MacroPrecision = ...
        mean(precision);

    metrics.MacroRecall = ...
        mean(recall);

    metrics.MacroF1 = ...
        mean(f1);

    metrics.MacroSpecificity = ...
        mean(specificity);

    metrics.MeanFAR = ...
        mean(far);

    metrics.MeanFRR = ...
        mean(frr);

    metrics.MeanEER = ...
        mean(eer);

    metrics.MeanAUC = ...
        mean(auc);

    User = ...
        (1:classCount)';

    userTable = table( ...
        User, ...
        userAccuracy, ...
        precision, ...
        recall, ...
        specificity, ...
        f1, ...
        far, ...
        frr, ...
        eer, ...
        auc, ...
        'VariableNames', { ...
        'User', ...
        'Accuracy', ...
        'Precision', ...
        'Recall', ...
        'Specificity', ...
        'F1', ...
        'FAR', ...
        'FRR', ...
        'EER', ...
        'AUC' ...
        });
end