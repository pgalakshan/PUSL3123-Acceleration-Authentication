    network.divideFcn = 'dividetrain';

    network.trainParam.epochs = maxEpochs;
    network.trainParam.showWindow = false;
    network.trainParam.showCommandLine = false;

    network.inputs{1}.processFcns = {};

    network = train( ...
        network, ...
        XTrainZ', ...
        targets);

    scores = ...
        network(XTestZ');

    [metrics, userMetrics] = ...
        authenticationMetrics( ...
        yMDay9, ...
        scores);

