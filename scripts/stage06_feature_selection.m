selectedEER = ...
    FeatureSelectionSummary.MeanEER(1);

%% Final mRMR ranking using all FDay
% Used only to define the locked feature list after the
% feature-count hyperparameter has already been selected.

[finalRanking, finalScores] = ...
    fscmrmr( ...
    X, ...
    categorical(labels));

lockedFeatures = ...
    finalRanking(1:selectedFeatureCount);

rankColumn = ...
    (1:selectedFeatureCount)';

