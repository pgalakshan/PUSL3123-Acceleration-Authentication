%% Supervised feature selection using mRMR
clear;
clc;
close all;

scriptPath = mfilename('fullpath');
projectRoot = fileparts(fileparts(scriptPath));

dataDir = fullfile(projectRoot, 'CW-Data');
tableDir = fullfile(projectRoot, 'results', 'tables');
figureDir = fullfile(projectRoot, 'results', 'figures');

if ~exist(tableDir, 'dir')
    mkdir(tableDir);
end

if ~exist(figureDir, 'dir')
    mkdir(figureDir);
end

%% Configuration

users = compose('U%02d', 1:10);

domain = 'TimeD_FreqD';
hiddenLayers = [48 24];

featureCounts = [20 40 60 80 100 131];

repeats = 5;
validationSamplesPerUser = 8;
maxEpochs = 400;

fprintf('\nStage 6 - mRMR Feature Selection\n');
fprintf('================================\n\n');

fprintf('Feature domain : %s\n', domain);
fprintf('Architecture   : [48 24]\n');
fprintf('Feature counts : ');

fprintf('%d ', featureCounts);

fprintf('\nRepeats        : %d\n', repeats);
fprintf('Total networks : %d\n\n', ...
    numel(featureCounts) * repeats);

%% Load FDay only

[X, labels] = loadDomainData( ...
    dataDir, ...
    domain, ...
    'FDay', ...
    users);

fprintf('FDay samples   : %d\n', size(X, 1));
fprintf('Original inputs: %d\n\n', size(X, 2));

%% Storage

resultRows = cell(0, 13);
resultRow = 1;

rankingRows = cell(0, 4);
rankingRow = 1;

rankingByRepeat = cell(repeats, 1);

%% Repeated development experiment

for repeat = 1:repeats

    fprintf('Repeat %d/%d\n', repeat, repeats);

    %% Identical stratified split for all feature counts

    rng(7200 + repeat, 'twister');

    trainMask = false(size(labels));
    validationMask = false(size(labels));

    for u = 1:10

        userIndices = find(labels == u);

        order = randperm(numel(userIndices));

        validationIndices = ...
            userIndices(order(1:validationSamplesPerUser));

        trainingIndices = ...
            userIndices(order(validationSamplesPerUser + 1:end));

        validationMask(validationIndices) = true;
        trainMask(trainingIndices) = true;
    end

    XTrainFull = X(trainMask, :);
    yTrain = labels(trainMask);

    XValidationFull = X(validationMask, :);
    yValidation = labels(validationMask);

    %% mRMR ranking fitted on training samples only

    [featureRanking, featureScores] = ...
        fscmrmr( ...
        XTrainFull, ...
        categorical(yTrain));

    rankingByRepeat{repeat} = featureRanking;

    for rankPosition = 1:numel(featureRanking)

        featureIndex = ...
            featureRanking(rankPosition);

        rankingRows(rankingRow, :) = { ...
            repeat, ...
            rankPosition, ...
            featureIndex, ...
            featureScores(featureIndex) ...
            };

        rankingRow = rankingRow + 1;
    end

    %% Evaluate different feature counts

    for c = 1:numel(featureCounts)

        featureCount = featureCounts(c);

        selectedFeatures = ...
            featureRanking(1:featureCount);

        XTrain = ...
            XTrainFull(:, selectedFeatures);

        XValidation = ...
            XValidationFull(:, selectedFeatures);

        %% Standardisation using training samples only

        mu = mean(XTrain, 1);
        sigma = std(XTrain, 0, 1);

        sigma(sigma == 0) = 1;

        XTrainZ = ...
            (XTrain - mu) ./ sigma;

        XValidationZ = ...
            (XValidation - mu) ./ sigma;

        %% Neural network

        rng( ...
            8200 + ...
            c * 100 + ...
            repeat, ...
            'twister');

        network = patternnet( ...
            hiddenLayers, ...
            'trainscg');

        network.performFcn = 'crossentropy';
        network.divideFcn = 'dividetrain';

        network.trainParam.epochs = maxEpochs;
        network.trainParam.showWindow = false;
        network.trainParam.showCommandLine = false;

        network.inputs{1}.processFcns = {};

        targets = ...
            full(ind2vec(yTrain'));

        network = train( ...
            network, ...
            XTrainZ', ...
            targets);

        validationScores = ...
            network(XValidationZ');

        metrics = ...
            authenticationMetrics( ...
            yValidation, ...
            validationScores);

        resultRows(resultRow, :) = { ...
            featureCount, ...
            repeat, ...
            metrics.Accuracy, ...
            metrics.MacroPrecision, ...
            metrics.MacroRecall, ...
            metrics.MacroF1, ...
            metrics.MacroSpecificity, ...
            metrics.MeanFAR, ...
            metrics.MeanFRR, ...
            metrics.MeanEER, ...
            metrics.MeanAUC, ...
            size(XTrain, 1), ...
            size(XTrain, 2) ...
            };

        resultRow = resultRow + 1;
    end
end

%% Save mRMR rankings

MRMRRankings = cell2table( ...
