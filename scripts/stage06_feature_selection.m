summaryRows = cell(numel(featureCounts), 12);

for c = 1:numel(featureCounts)

    featureCount = featureCounts(c);

    idx = ...
        FeatureSelectionRuns.FeatureCount == featureCount;

    current = ...
        FeatureSelectionRuns(idx, :);

